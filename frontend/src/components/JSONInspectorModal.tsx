import React, { useState } from 'react';
import { X, Copy, Check, Download, Code, ArrowUpRight, CheckCircle, AlertCircle } from 'lucide-react';
import { RecordedApiCall } from '../services/api';
import { soundManager } from '../utils/audio';

interface JSONInspectorModalProps {
  isOpen: boolean;
  onClose: () => void;
  recordedCalls: RecordedApiCall[];
  activePayload?: any;
  activeEndpointName?: string;
}

export const JSONInspectorModal: React.FC<JSONInspectorModalProps> = ({
  isOpen,
  onClose,
  recordedCalls,
  activePayload,
  activeEndpointName
}) => {
  const [selectedCallId, setSelectedCallId] = useState<string>('active');
  const [copied, setCopied] = useState<boolean>(false);
  const [viewTab, setViewTab] = useState<'response' | 'request' | 'full'>('response');

  if (!isOpen) return null;

  const currentCall = recordedCalls.find(c => c.id === selectedCallId) || recordedCalls[0];

  let displayData: any = null;
  let endpoint = activeEndpointName || currentCall?.endpoint || '/api/v1/recommendations';
  let status = currentCall?.status || 200;
  let timestamp = currentCall?.timestamp || new Date().toISOString();

  if (selectedCallId === 'active' && activePayload) {
    displayData = activePayload;
  } else if (currentCall) {
    if (viewTab === 'response') {
      displayData = currentCall.responsePayload;
    } else if (viewTab === 'request') {
      displayData = currentCall.requestPayload;
    } else {
      displayData = {
        endpoint: currentCall.endpoint,
        method: currentCall.method,
        status: currentCall.status,
        timestamp: currentCall.timestamp,
        duration_ms: currentCall.durationMs,
        request: currentCall.requestPayload,
        response: currentCall.responsePayload
      };
    }
  } else {
    displayData = activePayload || { message: 'No API calls recorded yet.' };
  }

  const jsonString = JSON.stringify(displayData, null, 2);

  const handleCopy = () => {
    soundManager.playClick();
    navigator.clipboard.writeText(jsonString);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    soundManager.playClick();
    const blob = new Blob([jsonString], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `terraform-${endpoint.replace(/[^a-zA-Z0-9]/g, '_')}-${Date.now()}.json`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div className="modal-content" style={{ maxWidth: '950px' }} onClick={e => e.stopPropagation()}>
        <div className="modal-header">
          <div style={{ display: 'flex', alignItems: 'center', gap: '12px' }}>
            <div style={{ padding: '8px', background: '#e8f5e9', borderRadius: '8px', color: '#1b4332' }}>
              <Code size={20} />
            </div>
            <div>
              <h3 style={{ fontSize: '1.2rem', fontWeight: 700 }}>Real Backend JSON Inspector</h3>
              <p style={{ fontSize: '0.8rem', color: 'var(--color-text-muted)' }}>
                Inspect live structured responses generated by the FastAPI backend
              </p>
            </div>
          </div>
          <button onClick={onClose} style={{ padding: '6px', borderRadius: '6px' }}>
            <X size={20} />
          </button>
        </div>

        <div style={{ padding: '16px 24px', background: 'var(--color-bg-subtle)', borderBottom: '1px solid var(--color-border-subtle)', display: 'flex', flexWrap: 'wrap', gap: '12px', alignItems: 'center', justifyContent: 'space-between' }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
            <span className="badge" style={{ background: '#1b4332', color: '#a7f3d0', fontFamily: 'var(--font-mono)' }}>
              {endpoint}
            </span>
            <span className="badge" style={{ background: status === 200 ? '#e8f5e9' : '#ffebee', color: status === 200 ? '#2e7d32' : '#c62828' }}>
              HTTP {status}
            </span>
            <span style={{ fontSize: '0.78rem', color: 'var(--color-text-muted)' }}>
              {new Date(timestamp).toLocaleTimeString()}
            </span>
          </div>

          <div style={{ display: 'flex', gap: '8px' }}>
            {recordedCalls.length > 0 && (
              <select
                value={selectedCallId}
                onChange={e => setSelectedCallId(e.target.value)}
                style={{ padding: '6px 10px', borderRadius: '6px', border: '1px solid var(--color-border-card)', fontSize: '0.82rem', background: '#fff' }}
              >
                {activePayload && <option value="active">Active View Payload</option>}
                {recordedCalls.map(c => (
                  <option key={c.id} value={c.id}>
                    [{c.method}] {c.endpoint} ({c.status})
                  </option>
                ))}
              </select>
            )}

            <div style={{ display: 'flex', background: '#fff', borderRadius: '6px', border: '1px solid var(--color-border-card)', overflow: 'hidden' }}>
              <button
                onClick={() => setViewTab('response')}
                style={{ padding: '5px 12px', fontSize: '0.78rem', fontWeight: 600, background: viewTab === 'response' ? 'var(--color-forest-medium)' : 'transparent', color: viewTab === 'response' ? '#fff' : 'inherit' }}
              >
                Response
              </button>
              <button
                onClick={() => setViewTab('request')}
                style={{ padding: '5px 12px', fontSize: '0.78rem', fontWeight: 600, background: viewTab === 'request' ? 'var(--color-forest-medium)' : 'transparent', color: viewTab === 'request' ? '#fff' : 'inherit' }}
              >
                Request
              </button>
              <button
                onClick={() => setViewTab('full')}
                style={{ padding: '5px 12px', fontSize: '0.78rem', fontWeight: 600, background: viewTab === 'full' ? 'var(--color-forest-medium)' : 'transparent', color: viewTab === 'full' ? '#fff' : 'inherit' }}
              >
                Full Exchange
              </button>
            </div>
          </div>
        </div>

        <div className="modal-body" style={{ maxHeight: '60vh', overflowY: 'auto' }}>
          <pre className="json-code">
            {jsonString}
          </pre>
        </div>

        <div className="modal-footer" style={{ justifyContent: 'space-between' }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: '6px', fontSize: '0.8rem', color: 'var(--color-text-muted)' }}>
            <CheckCircle size={14} color="#2d6a4f" /> Verified live payload from FastAPI SQLite database engine
          </div>

          <div style={{ display: 'flex', gap: '10px' }}>
            <button className="btn btn-outline btn-sm" onClick={handleCopy}>
              {copied ? <Check size={14} color="#2e7d32" /> : <Copy size={14} />}
              <span>{copied ? 'Copied!' : 'Copy JSON'}</span>
            </button>
            <button className="btn btn-sage btn-sm" onClick={handleDownload}>
              <Download size={14} />
              <span>Download .json</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
